/**
 * @file results-pdf.tsx
 * @description Full Results PDF document component.
 * Generates a styled PDF matching the app's results page design.
 */

import { Document, Page, View, Text, StyleSheet, pdf } from '@react-pdf/renderer';
import type { FullAssessment } from '@/types/assessment';
import type { Language } from '@/lib/i18n';
import { t } from '@/lib/i18n';
import { IKIGAI_COLORS } from '../shared/colors';
import { CoreDriversPDF } from './core-drivers-pdf';
import { PurposePathPDF } from './purpose-path-pdf';

// Import fonts (side effect registration)
import '../shared/fonts';

const styles = StyleSheet.create({
  page: {
    backgroundColor: IKIGAI_COLORS.beige,
    padding: 40,
    fontFamily: 'Helvetica',
  },

  // Header section
  header: {
    marginBottom: 24,
    textAlign: 'center',
  },
  title: {
    fontFamily: 'Helvetica-Bold',
    fontSize: 28,
    color: IKIGAI_COLORS.slate900,
    marginBottom: 8,
  },
  subtitle: {
    fontFamily: 'Helvetica',
    fontSize: 12,
    color: IKIGAI_COLORS.slate600,
  },

  // Section header
  sectionHeader: {
    fontFamily: 'Helvetica-Bold',
    fontSize: 20,
    color: IKIGAI_COLORS.slate900,
    textAlign: 'center',
    marginBottom: 20,
    marginTop: 8,
  },

  // Path cards container
  pathsContainer: {
    flexDirection: 'column',
    gap: 16,
  },

  // Footer
  footer: {
    position: 'absolute',
    bottom: 30,
    left: 40,
    right: 40,
    textAlign: 'center',
    fontFamily: 'Helvetica',
    fontSize: 9,
    color: IKIGAI_COLORS.slate500,
  },
});

interface ResultsPDFProps {
  results: FullAssessment;
  language: Language;
}

function ResultsPDF({ results, language }: ResultsPDFProps) {
  // Early return if no analysis data
  if (!results.coreDriversAnalysis) {
    return (
      <Document>
        <Page size="A4" style={styles.page}>
          <Text>No analysis data available</Text>
        </Page>
      </Document>
    );
  }

  return (
    <Document>
      <Page size="A4" style={styles.page}>
        {/* Header */}
        <View style={styles.header}>
          <Text style={styles.title}>{t('results.title', language)}</Text>
        </View>

        {/* Core Drivers Summary */}
        <CoreDriversPDF
          analysis={results.coreDriversAnalysis}
          language={language}
        />

        {/* Purpose Paths Section Title */}
        <Text style={styles.sectionHeader}>
          {t('results.purposePaths', language)}
        </Text>

        {/* Purpose Path Cards */}
        <View style={styles.pathsContainer}>
          {results.purposePaths.map((path, index) => (
            <PurposePathPDF
              key={path.id}
              path={path}
              index={index}
              language={language}
            />
          ))}
        </View>

        {/* Footer */}
        <Text style={styles.footer}>
          Generated by Ikigai Finder
        </Text>
      </Page>
    </Document>
  );
}

/**
 * Generates and downloads the Results PDF.
 * Uses dynamic rendering with react-pdf's pdf() function.
 */
export async function generateResultsPDF(
  results: FullAssessment,
  language: Language
): Promise<void> {
  const blob = await pdf(<ResultsPDF results={results} language={language} />).toBlob();
  const url = URL.createObjectURL(blob);

  const link = document.createElement('a');
  link.href = url;
  link.download = language === 'en' ? 'ikigai-analysis.pdf' : 'analisis-ikigai.pdf';
  link.click();

  // Cleanup
  URL.revokeObjectURL(url);
}
